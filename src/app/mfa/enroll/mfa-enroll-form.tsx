"use client";

import { useState } from "react";
import { useRouter } from "next/navigation";
import { createClient } from "@/lib/supabase/client";

type Enrollment = {
  factorId: string;
  qrCode: string;
  secret: string;
};

export function MfaEnrollForm() {
  const router = useRouter();
  const [enrollment, setEnrollment] = useState<Enrollment | null>(null);
  const [code, setCode] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  const startEnrollment = async () => {
    setBusy(true);
    setError(null);
    try {
      const supabase = createClient();
      const { data, error: enrollError } = await supabase.auth.mfa.enroll({
        factorType: "totp",
        friendlyName: "PlumWorks",
      });
      if (enrollError) throw enrollError;
      if (!data.totp) throw new Error("Authenticator setup information was not returned.");

      setEnrollment({
        factorId: data.id,
        qrCode: data.totp.qr_code,
        secret: data.totp.secret,
      });
    } catch (err) {
      setError(err instanceof Error ? err.message : "Unable to start authenticator setup.");
    } finally {
      setBusy(false);
    }
  };

  const verifyEnrollment = async () => {
    if (!enrollment || code.trim().length !== 6) return;
    setBusy(true);
    setError(null);
    try {
      const supabase = createClient();
      const challenge = await supabase.auth.mfa.challenge({ factorId: enrollment.factorId });
      if (challenge.error) throw challenge.error;

      const verification = await supabase.auth.mfa.verify({
        factorId: enrollment.factorId,
        challengeId: challenge.data.id,
        code: code.trim(),
      });
      if (verification.error) throw verification.error;

      router.replace("/dashboard");
      router.refresh();
    } catch {
      setError("That code could not be verified. Enter the current 6-digit code from your authenticator app.");
    } finally {
      setBusy(false);
    }
  };

  const signOut = async () => {
    const supabase = createClient();
    await supabase.auth.signOut();
    router.replace("/login");
    router.refresh();
  };

  const qrSource = enrollment
    ? enrollment.qrCode.startsWith("data:")
      ? enrollment.qrCode
      : `data:image/svg+xml;utf8,${encodeURIComponent(enrollment.qrCode)}`
    : null;

  return (
    <div className="mt-6 space-y-5">
      {!enrollment ? (
        <button
          type="button"
          onClick={startEnrollment}
          disabled={busy}
          className="w-full rounded-lg bg-brand-primary px-4 py-2.5 text-sm font-semibold text-white disabled:opacity-60"
        >
          {busy ? "Preparing…" : "Set up authenticator app"}
        </button>
      ) : (
        <>
          <div className="rounded-xl border border-slate-200 bg-slate-50 p-4 text-center">
            {qrSource ? (
              // The QR code is generated by Supabase Auth for this signed-in user.
              // eslint-disable-next-line @next/next/no-img-element
              <img src={qrSource} alt="Authenticator enrollment QR code" className="mx-auto h-52 w-52 bg-white p-2" />
            ) : null}
            <p className="mt-4 text-sm text-slate-600">
              Scan this QR code with Google Authenticator, then enter the current 6-digit code below.
            </p>
            <details className="mt-3 text-left text-sm text-slate-600">
              <summary className="cursor-pointer font-medium text-brand-primary">Can’t scan the QR code?</summary>
              <p className="mt-2 break-all rounded bg-white p-2 font-mono text-xs">{enrollment.secret}</p>
            </details>
          </div>

          <label className="block">
            <span className="text-sm font-medium text-slate-700">6-digit authenticator code</span>
            <input
              value={code}
              onChange={(event) => setCode(event.target.value.replace(/\D/g, "").slice(0, 6))}
              inputMode="numeric"
              autoComplete="one-time-code"
              maxLength={6}
              className="mt-2 w-full rounded-lg border border-slate-300 px-3 py-2.5 text-center font-mono text-xl tracking-[0.35em] text-slate-950 outline-none focus:border-brand-primary focus:ring-2 focus:ring-brand-subtle"
            />
          </label>

          <button
            type="button"
            onClick={verifyEnrollment}
            disabled={busy || code.length !== 6}
            className="w-full rounded-lg bg-brand-primary px-4 py-2.5 text-sm font-semibold text-white disabled:opacity-60"
          >
            {busy ? "Verifying…" : "Verify and continue"}
          </button>
        </>
      )}

      {error ? <p role="alert" className="rounded-lg border border-red-200 bg-red-50 px-3 py-2.5 text-sm text-red-700">{error}</p> : null}

      <button type="button" onClick={signOut} className="w-full text-sm font-medium text-slate-500 hover:text-slate-700">
        Sign out
      </button>
    </div>
  );
}
